/**
 * `image_list` 的单条（前端九宫格 / 管理页用）。
 *
 * ⚠️ 不含本地路径：预览统一走 `imageLoadDataUrl(id)`，
 * 避免把 `app_data` 内部路径泄漏给 webview，也避免路径随重装失效。
 *
 * 见 docs/08-IPC契约.md §3 组 14。
 */
export interface ImageCacheItem {
  /** 图片 ID（落盘文件名是 `<sha1>.<ext>`，ID 是另发的 UUID） */
  id: string
  /** 占用字节（文件真实大小） */
  sizeBytes: number
  /** 入库时间（毫秒） */
  createdAt: number
  /** 被引用处数（被多少条输入历史 / 公式 / 附件引用） */
  refCount: number
}
